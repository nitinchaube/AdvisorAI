// Helper function to get theme by name
export const getTheme = (themeName = "slate") => {
  return portfolioThemes[themeName] || portfolioThemes.slate;
};

// Helper function to get all theme names for selection
export const getThemeOptions = () => {
  return Object.entries(portfolioThemes).map(([key, theme]) => ({
    value: key,
    label: theme.name,
    description: theme.description,
    preview: theme.colors,
  }));
};

// Helper function to generate Tailwind CSS classes
